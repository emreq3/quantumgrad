GLOSSARY = [
    {"term": "Qubit", "def": "A two-level quantum system; its state can be a superposition of 0 and 1."},
    {"term": "Pauli error", "def": "X flips 0 and 1, Z flips the sign of the 1 component, Y is both. Any single-qubit error can be expanded in Pauli operators."},
    {"term": "Fidelity", "def": "Overlap between the actual state and the ideal state (1 = perfect). Conditional fidelity is measured only on accepted shots."},
    {"term": "Spacetime check", "def": "An ancilla qubit entangled with a data qubit at several moments; its measurement flags faults the check can see."},
    {"term": "Post-selection", "def": "Keeping only shots whose syndrome is trivial. It raises fidelity but lowers the acceptance probability (kappa)."},
    {"term": "Error mitigation", "def": "A classical-post-processing technique that improves an *estimate* of an observable. It does not repair the quantum state."},
    {"term": "Zero-noise extrapolation", "def": "Measure at amplified noise levels, then extrapolate to zero noise. Lowers bias, raises variance."},
    {"term": "MSE", "def": "Mean squared error = bias^2 + variance."},
    {"term": "Syndrome", "def": "The pattern of stabilizer outcomes that signals where errors may have occurred."},
    {"term": "MWPM", "def": "Minimum-weight perfect matching: a decoder pairing defects (or sending them to a boundary) at least total cost."},
    {"term": "Logical error", "def": "A residual error that acts on the encoded information although the syndrome is clean."},
    {"term": "Code distance", "def": "The size of the smallest undetectable logical error; larger distance needs more qubits."},
    {"term": "Pareto front", "def": "The candidates that no other candidate beats on every objective."},
    {"term": "Quantum credits", "def": "Fictional game currency used to price actions. Not related to any real quantum-cloud credits."},
]
