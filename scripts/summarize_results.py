"""Write docs/benchmark_results.md and docs/performance_report.md directly from results/*.json (no hand-copied numbers)."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
P = "standard"


def L(sub, name):
    return json.loads((RES / sub / f"{name}_{P}.json").read_text())


def ms(xs):
    xs = [x for x in xs if x is not None]
    return (float(np.mean(xs)), float(np.std(xs, ddof=1)) if len(xs) > 1 else 0.0, len(xs))


def main() -> None:
    det, mit, cor, opt, perf = L("detection", "detection"), L("mitigation", "mitigation"), L("correction", "correction"), L("optimization", "optimization"), L("optimization", "performance")
    meta = det["meta"]
    out = ["# Benchmark results (standard profile)", "",
           f"Generated by `scripts/summarize_results.py` from `results/**/*_standard.json` — source revision `{meta['source_revision']}`, qta6 {meta['qta6']}, "
           f"Qiskit {meta['software']['qiskit']}, Aer {meta['software']['qiskit-aer']}, qiskit-paulice {meta['software']['qiskit-paulice']}, Stim {meta['software']['stim']}, "
           f"PyMatching {meta['software']['pymatching']}, Python {meta['software']['python']}. **All noise profiles are synthetic; none is a device measurement.** "
           "Figures: `results/figures/`.", ""]
    # ---------------- detection
    rows = [r for r in det["rows"] if r["status"] == "ok"]
    ns = [r for r in rows if r["group"] == "noise_sweep"]
    out += ["## 1. Error detection (exact density-matrix simulation; n=4 unless stated; mean ± sd over payload seeds)", "",
            "Noise sweep, depth 6 — post-selected fidelity `F_ps`, acceptance `κ`, extra two-qubit gates (readout error 1% on ancillas):", "",
            "| p2 | checks | unprotected F | post-selected F_ps | κ | extra 2q gates | n |", "|---|---|---|---|---|---|---|"]
    for p2 in sorted({r["p2"] for r in ns}):
        for k in sorted({r["checks"] for r in ns}):
            rr = [r for r in ns if r["p2"] == p2 and r["checks"] == k]
            if not rr:
                continue
            f0, fps, kap, g = ms([r["unprotected"] for r in rr]), ms([r["postselected"] for r in rr]), ms([r["acceptance"] for r in rr]), ms([r["extra_2q"] for r in rr])
            out.append(f"| {p2} | {k} | {f0[0]:.4f} ± {f0[1]:.4f} | {fps[0]:.4f} ± {fps[1]:.4f} | {kap[0]:.3f} ± {kap[1]:.3f} | {g[0]:.1f} | {fps[2]} |")
    best = max((r for r in rows if r["checks"] > 0 and r["group"] == "noise_sweep"), key=lambda r: r["postselected"] - r["unprotected"])
    out += ["", f"Largest gain in the noise sweep: Δ = {best['postselected'] - best['unprotected']:+.4f} (F {best['unprotected']:.4f} → {best['postselected']:.4f}) with {best['checks']} checks at p2={best['p2']}, κ = {best['acceptance']:.3f}.", ""]
    dd = [r for r in rows if r["group"] == "depth_sweep" and r["checks"] > 0]
    out += ["Depth sweep (p2 = 0.01): Δ fidelity = F_ps − F_unprotected (mean over seeds)", "", "| depth | 1 check | 2 checks | 3 checks |", "|---|---|---|---|"]
    for d in sorted({r["depth"] for r in dd}):
        cells = []
        for k in (1, 2, 3):
            v = ms([r["postselected"] - r["unprotected"] for r in dd if r["depth"] == d and r["checks"] == k])
            cells.append(f"{v[0]:+.4f} ± {v[1]:.4f}" if v[2] else "n/a")
        out.append(f"| {d} | " + " | ".join(cells) + " |")
    neg = [r for r in rows if r["group"] in ("noise_sweep", "depth_sweep", "width_sweep") and r["checks"] > 0 and r["postselected"] <= r["unprotected"]]
    tot = [r for r in rows if r["group"] in ("noise_sweep", "depth_sweep", "width_sweep") and r["checks"] > 0]
    out += ["", f"**Negative results (kept):** in {len(neg)} of {len(tot)} protected runs the post-selected fidelity was not above the unprotected fidelity "
            f"(depths {sorted({r['depth'] for r in neg})}, widths {sorted({r['n'] for r in neg})}). The `paradox` group (n=4, depth 2, p2=0.02, 2 checks): "
            + ", ".join(f"seed {r['seed']}: Δ={r['postselected'] - r['unprotected']:+.4f}" for r in rows if r["group"] == "paradox") + ".", ""]
    npl = [r for r in det["rows"] if r["status"] != "ok"]
    out += [f"Not placeable (Paulice could not place the requested number of checks): {len(npl)} configurations, e.g. widths {sorted({r['n'] for r in npl})}.", ""]
    ct = [r for r in rows if r["group"] == "clifford_vs_t"]
    out += ["### Clifford vs Clifford+T (n=4, depth 6, p2=0.01; fidelity measured against the *intended* T-doped state)", "",
            "| checks | T gates | placement | F_unprotected (same data gates) | F_ps | κ | invalidated-check fraction |", "|---|---|---|---|---|---|---|"]
    for k in (0, 2, 3):
        for t in sorted({r["t"] for r in ct}):
            for pl in ("safe", "blind"):
                rr = [r for r in ct if r["checks"] == k and r["t"] == t and r["placement"] == pl]
                if not rr or (t == 0 and pl == "blind"):
                    continue
                out.append(f"| {k} | {t} | {pl} | {ms([r['unprotected'] for r in rr])[0]:.4f} | {ms([r['postselected'] for r in rr])[0]:.4f} | "
                           f"{ms([r['acceptance'] for r in rr])[0]:.3f} | {np.mean([not r['checks_valid'] for r in rr]):.2f} |")
    out += [""]
    # ---------------- mitigation
    rows = mit["rows"]
    out += [f"## 2. Error mitigation (fixed total raw-shot budget; {rows[0]['trials']} independent trials per cell; exact noisy distributions from Aer, sampled shots)", "",
            "MSE of the observable estimate, mean over two task instances (budget includes calibration and pilot shots):", "",
            "| profile | budget | unmitigated | readout (tensor) | ZNE linear (1,3) | ZNE Richardson (1,3,5) uniform | adaptive | oracle | readout+ZNE linear |", "|---|---|---|---|---|---|---|---|---|"]
    names = ["unmitigated", "readout_tensor", "zne_linear_uniform", "zne_richardson3_uniform", "zne_richardson3_adaptive", "zne_richardson3_oracle", "readout+zne_linear"]
    for pn in sorted({r["profile"] for r in rows}):
        for b in sorted({r["budget"] for r in rows}):
            cells = []
            for n in names:
                v = ms([r["mse"] for r in rows if r["profile"] == pn and r["budget"] == b and r["strategy"] == n])
                cells.append(f"{v[0]:.2e}" if v[2] else "n/a")
            out.append(f"| {pn} | {b} | " + " | ".join(cells) + " |")
    worse = [r for r in rows if r["strategy"] != "unmitigated" and r["mse_ratio_vs_unmitigated"] and r["mse_ratio_vs_unmitigated"] > 1.0]
    better = [r for r in rows if r["strategy"] != "unmitigated" and r["mse_ratio_vs_unmitigated"] and r["mse_ratio_vs_unmitigated"] < 1.0]
    out += ["", f"Failure regimes (kept): {len(worse)} of {len(worse) + len(better)} (strategy, budget, profile, instance) cells had **higher** MSE than the unmitigated estimate at the same total budget; "
            f"{len(better)} had lower. Example variance trap (gate-dominated): ", ""]
    for b in (2000, 8000):
        for n in ("unmitigated", "zne_richardson3_uniform"):
            rr = [r for r in rows if r["profile"] == "gate_dominated" and r["budget"] == b and r["strategy"] == n]
            if rr:
                out.append(f"- budget {b}, {n}: bias {ms([r['bias'] for r in rr])[0]:+.4f}, variance {ms([r['variance'] for r in rr])[0]:.2e}, MSE {ms([r['mse'] for r in rr])[0]:.2e}")
    out += [""]
    # adaptive vs uniform
    out += ["Adaptive (pilot-shot) vs uniform vs oracle allocation, 3-point Richardson ZNE (gate-dominated):", "", "| budget | uniform MSE | adaptive MSE | oracle MSE | adaptive/uniform | oracle/uniform |", "|---|---|---|---|---|---|"]
    for b in sorted({r["budget"] for r in rows}):
        v = {n: ms([r["mse"] for r in rows if r["profile"] == "gate_dominated" and r["budget"] == b and r["strategy"] == n])[0] for n in ("zne_richardson3_uniform", "zne_richardson3_adaptive", "zne_richardson3_oracle")}
        out.append(f"| {b} | {v['zne_richardson3_uniform']:.2e} | {v['zne_richardson3_adaptive']:.2e} | {v['zne_richardson3_oracle']:.2e} | {v['zne_richardson3_adaptive'] / v['zne_richardson3_uniform']:.2f} | {v['zne_richardson3_oracle'] / v['zne_richardson3_uniform']:.2f} |")
    out += ["", "The oracle uses the true per-term standard deviations (information a player does not have); it is an ideal reference, not an achievable strategy.", ""]
    # ---------------- correction
    rows = cor["rows"]
    out += ["## 3. Error correction (rotated surface code memory, circuit-level depolarizing noise, d rounds, Stim + PyMatching MWPM)", "",
            "Logical failure = predicted logical flip ≠ simulated observable flip. Fixed-sample experiments (no adaptive stopping). Intervals: 95% Wilson (Clopper–Pearson in the JSON).", "",
            "| d | active qubits | p | trials | failures | p_L | 95% Wilson | qubit-rounds | decode µs/shot |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["distance"], r["p"])):
        e = r["estimate"]
        ub = f" (0 failures: 95% upper bound {r['upper_bound_if_zero']:.2e})" if r["upper_bound_if_zero"] else ""
        out.append(f"| {r['distance']} | {r['active_qubits']} | {r['p']} | {r['trials']} | {r['failures']} | {e['p']:.2e}{ub} | [{e['wilson95'][0]:.2e}, {e['wilson95'][1]:.2e}] | {r['qubit_rounds']} | {r['decode_us_per_shot']:.1f} |")
    ps = sorted({r["p"] for r in rows})
    cross = []
    for p in ps:
        e = {r["distance"]: r["estimate"]["p"] for r in rows if r["p"] == p}
        cross.append(f"p={p}: " + " → ".join(f"d{d}={e[d]:.2e}" for d in sorted(e)))
    out += ["", "Distance ordering by physical error rate:", ""] + [f"- {c}" for c in cross]
    below = [p for p in ps if {r["distance"]: r["estimate"]["p"] for r in rows if r["p"] == p}[7] < {r["distance"]: r["estimate"]["p"] for r in rows if r["p"] == p}[3]]
    above = [p for p in ps if p not in below]
    out += ["", f"Observed: larger distance gives lower p_L for p ∈ {below} and higher p_L for p ∈ {above}. "
            "This brackets the crossover between those grid points for *this* noise model and decoder; **no threshold value is claimed** (the grid is too coarse and the sample sizes fixed).", ""]
    out += ["Repetition code (exact statevector, one logical state): all single X errors corrected = "
            f"{all(o['corrected'] for o in cor['repetition_code'] if o['error'].startswith('X') or o['error'] == 'none')}; "
            f"Y/Z errors corrected = {any(o['corrected'] for o in cor['repetition_code'] if o['error'][0] in 'YZ')} (expected False).", ""]
    # ---------------- optimization
    out += ["## 4. Optimization", "", f"Pareto fronts (exact extraction over the enumerated candidate sets): detection {len(opt['pareto_fronts']['detection']['front'])} of "
            f"{len(opt['pareto_fronts']['detection']['candidates'])} feasible candidates; mitigation {len(opt['pareto_fronts']['mitigation']['front'])} of {len(opt['pareto_fronts']['mitigation']['candidates'])}; "
            f"correction {len(opt['pareto_fronts']['correction']['front'])} of {len(opt['pareto_fronts']['correction']['candidates'])}.", ""]
    dr = opt["drift"]
    out += [f"Calibration drift (true noise = estimate drifted ×2.5; out-of-sample seeds): the strategy that is best under the stale calibration (`{dr['stale_best_key']}`) has true regret "
            f"{100 * dr['stale_best_true_regret']:.0f}% relative to the best strategy under the true noise; the robust choice (`{dr['robust_key']}`) has regret "
            f"{100 * min(v['regret_ratio'] for k, v in dr['outcomes'].items() if v['robust'] and not v['bought']):.0f}%. Buying a fresh calibration costs 10% of the shots.", ""]
    jb = opt["joint_baselines"]
    out += ["Baselines on the joint-budget missions (automated enumeration; **optimal only within the enumerated candidate set**; not a user study):", "",
            "| mission | enumerated plans | feasible | successful | random feasible: mean score (success rate) | greedy sequential | best enumerated |", "|---|---|---|---|---|---|---|"]
    for m, b in jb.items():
        out.append(f"| {m} | {b['n_rows']} | {b['n_feasible']} | {b['n_successful']} | {b['random_feasible']['mean_score']:.1f} ({100 * b['random_feasible']['success_rate']:.1f}%) | "
                   f"{b['greedy_sequential']['score']:.1f} | {b['best_enumerated']['score']:.1f} |")
    out += [""]
    (ROOT / "docs" / "benchmark_results.md").write_text("\n".join(out) + "\n")
    # ---------------- performance
    t = perf["timings"]
    pr = ["# Performance report", "", f"Measured by `python -m qta6.cli benchmark --profile standard --only performance` on: {perf['meta']['machine']['cpu_count']} CPU cores, {perf['meta']['machine']['platform']}, Python {perf['meta']['software']['python']}. "
          "Wall-clock medians and p95 over repeated runs after warm-up; single process. Numbers are machine dependent.", "",
          "| step | median (ms) | p95 (ms) | reps |", "|---|---|---|---|"]
    for k, v in t.items():
        if "median_ms" in v:
            pr.append(f"| {k} | {v['median_ms']:.3f} | {v['p95_ms']:.3f} | {v['reps']} |")
        else:
            pr.append(f"| {k} | {v['value']:.0f} (shots/s) | — | — |")
    pr += ["", "Initialization vs steady state: Stim circuit generation, detector-error-model construction and matching initialization are one-off per (d, rounds, p) and cached (`lru_cache`) by the engine; "
           "per-shot decoding and batched decoding are the steady-state costs. Scenario serialization is performed once by `qta6.cli export` (≈15 s for the standard profile, 3.3 MB JSON); "
           "the browser only loads and replays this file. Frontend production bundle: see `docs/frontend_and_api.md`.", ""]
    (ROOT / "docs" / "performance_report.md").write_text("\n".join(pr) + "\n")
    print("wrote docs/benchmark_results.md and docs/performance_report.md")


if __name__ == "__main__":
    main()
