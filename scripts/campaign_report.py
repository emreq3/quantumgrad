"""Generate docs/campaign_validation.md from the committed campaign data and the recorded browser playthrough.

Engine-level solvability (``qta6.game.solvability``) and the real-browser playthrough (``frontend/e2e/campaign.cjs``) are both automated
checks; neither is a human user study.
"""
from __future__ import annotations

import json
from pathlib import Path

from qta6.game.engine import _units
from qta6.game.economy import credit_cost
from qta6.game.solvability import action_space_summary, mission_issues, play_campaign, winning_actions, winning_corrections

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "frontend/public/data/campaign.json").read_text())
e2e_path = ROOT / "results/e2e/campaign_playthrough.json"
e2e = json.loads(e2e_path.read_text()) if e2e_path.exists() else {"missions": {}, "totals": {}}
play = play_campaign(data)
gen = data["generator"]

rows = []
for m in data["missions"]:
    s = action_space_summary(m)
    issues = mission_issues(m)
    if m["kind"] == "decoding":
        wins = winning_corrections(m)
        space = f"{len(wins)} instances, all with a winning correction"
    elif m["kind"] == "diagnosis":
        space = "1 diagnosis (set of consistent faults)"
    elif m["kind"] == "repetition":
        space = f"{s['actions']} actions, {s['successful']} winning"
    else:
        cheapest = min(credit_cost(_units(m, m['outcomes'][k])) for k in winning_actions(m))
        space = f"{s['actions']} actions, {s['feasible']} feasible, {s['winning_affordable']} winning (cheapest {cheapest:.1f} credits of {m['resources']['credits']})"
    b = e2e["missions"].get(m["id"], {})
    rows.append(f"| {m['id']} | {m['title']} | {m['district'].replace('_', ' ')} | {m['kind']} | {m['difficulty']} | {', '.join(m['unlock_requires']) or '—'} | {space} | "
                f"{'PASS' if not issues else 'FAIL'} | {b.get('status', 'not run')} |")

out = f"""# Campaign validation

Generated by `python scripts/campaign_report.py` from `frontend/public/data/campaign.json` (exported at revision `{gen['source_revision']}`, profile `{gen['profile']}`)
and `results/e2e/campaign_playthrough.json`. **Both checks are automated; neither is a human user study.**

* **Engine-level solvability** (`src/qta6/game/solvability.py`, tests in `tests/gameplay/test_campaign_solvability.py`): for every mission a winning
  strategy is constructed from the executed action space and played through the real `Game` state machine (select → begin → act → finish), so wallets,
  caps, unlock rules and transitions are exercised. The exporter refuses to build a mission with no affordable winning strategy.
* **Real-browser playthrough** (`frontend/e2e/campaign.cjs`): Chromium plays all {len(data['missions'])} missions from a fresh save through the production build, in unlock order,
  using only the visible UI, then reaches the campaign-complete screen.

Results: engine completes the whole campaign in unlock order = **{play['complete']}**; browser playthrough: **{e2e['totals'].get('passed', '?')} / {e2e['totals'].get('missions', '?')}** missions passed in
{e2e['totals'].get('seconds', '?')} s, campaign-complete screen reached = **{e2e['totals'].get('campaign_complete_screen', '?')}**, console errors during the run: **{len(e2e.get('issues', []))}**.

| id | title | district | kind | difficulty | requires | executed action space (current data) | engine solvable | browser |
|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + f"""

## Defects this audit found in the Phase 3 campaign

* **M3 *Zero Noise* could not be completed**: four configurations met the scientific goal, but every action spends the whole 40 000-shot budget (80 credits) and the mission granted 60. M4, M5, M6 and everything downstream (including N1) were therefore unreachable. Budget raised to 90 credits; the exporter now fails the build if any mission lacks an affordable winning strategy.
* **D1 and D4 were won by doing nothing**: the *gain over the unprotected circuit* condition was skipped when no check was placed. It is now always evaluated (D1: 15 → 14 winning configurations; D4: 22 → 20). D5 (*Protection Paradox*) intentionally still accepts "no protection" — that is its lesson.
* **O2, O4 and N1 charged nothing**: their exported actions had empty resource units, so budgets did not constrain exploration. Every outcome now exports the units it consumes; the wallet charges them (tests: `test_plan_missions_charge_the_wallet`, `hardening.test.tsx`).
* Nothing was edited by hand: the data was regenerated with the real engine and every physical outcome (fidelities, MSE, logical failure rates) is bit-identical to the previous export (see `docs/phase4_scientific_audit.md`).

## What is *not* covered

Human playtesting (difficulty, comprehension and enjoyment are untested), long-run balance of the pedagogical score weights, and mobile *gameplay* on a physical device (layout is audited in an emulated Chromium viewport, see `docs/browser_test_report.md`).
"""
(ROOT / "docs/campaign_validation.md").write_text(out)
print("wrote docs/campaign_validation.md")
