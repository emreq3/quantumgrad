export const f3 = (x: number | null | undefined, n = 3) => (x === null || x === undefined || Number.isNaN(x) ? "n/a" : x.toFixed(n));

const KIND_LABEL: Record<string, string> = {
  exact_numerical: "exact numerical simulation — precomputed, replayed",
  monte_carlo: "Monte Carlo simulation — precomputed, replayed",
  analytical: "analytical result",
};
export function ProvenanceBadge({ kind }: { kind?: string }) {
  const label = KIND_LABEL[kind ?? "exact_numerical"] ?? kind ?? "precomputed";
  return <span className="badge" title="Generated by validated quantum simulations in the project's Python engine and replayed from precomputed experiment data; the browser does not run quantum simulations.">⏺ {label}</span>;
}

/** Modal dialog with focus management: focus moves in, Tab is trapped, Escape closes, focus returns to the opener. */
export function Dialog({ title, onClose, children, actions }: { title: string; onClose: () => void; children: ReactNode; actions?: ReactNode }) {
  const id = useId();
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const opener = document.activeElement as HTMLElement | null;
    const focusables = () => Array.from(ref.current?.querySelectorAll<HTMLElement>("button,[href],input,select,textarea,[tabindex]:not([tabindex='-1'])") ?? []).filter((e) => !e.hasAttribute("disabled"));
    (focusables()[0] ?? ref.current)?.focus();
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") { e.stopPropagation(); onClose(); return; }
      if (e.key !== "Tab") return;
      const f = focusables();
      if (!f.length) return;
      const first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    };
    document.addEventListener("keydown", onKey, true);
    return () => { document.removeEventListener("keydown", onKey, true); opener?.focus?.(); };
  }, [onClose]);
  return (
    <div className="overlay" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className="dialog" role="dialog" aria-modal="true" aria-labelledby={id} ref={ref} tabIndex={-1}>
        <h2 id={id}>{title}</h2>
        {children}
        {actions && <div className="row" style={{ justifyContent: "flex-end" }}>{actions}</div>}
      </div>
    </div>
  );
}

export function ConfirmDialog({ title, body, confirm, cancel = "Cancel", onConfirm, onCancel, danger }: { title: string; body: ReactNode; confirm: string; cancel?: string; onConfirm: () => void; onCancel: () => void; danger?: boolean }) {
  return (
    <Dialog title={title} onClose={onCancel} actions={<><button onClick={onCancel}>{cancel}</button><button className={danger ? "danger" : "primary"} onClick={onConfirm}>{confirm}</button></>}>
      <div>{body}</div>
    </Dialog>
  );
}

const RES_LABEL: Record<string, string> = { ancilla_qubits: "Ancillas", extra_two_qubit_gates: "Extra 2-qubit gates", shots: "Shots", physical_qubits: "Physical qubits", qubit_rounds: "Qubit-rounds", calibration_refresh: "Calibrations" };

/** HUD resource strip. The wallet in the game store is the only source of truth; the highlight is cosmetic. */
export function ResourceBar() {
  const { wallet, lastSpend, mission, last } = useGame();
  const prev = useRef<{ n: number }>({ n: 0 });
  const [bump, setBump] = useState<{ n: number; keys: string[] } | null>(null);
  useEffect(() => {
    if (!lastSpend || lastSpend.n === prev.current.n) return;
    prev.current = { n: lastSpend.n };
    const keys = ["credits", ...Object.keys(lastSpend.units).filter((k) => wallet && k in wallet.caps)];
    setBump({ n: lastSpend.n, keys });
    const t = setTimeout(() => setBump(null), 1600);
    return () => clearTimeout(t); // never leaves a timer behind
  }, [lastSpend, wallet]);
  if (!wallet) return null;
  const caps = Object.entries(wallet.caps).filter(([k]) => k !== "credits");
  const item = (k: string, label: string, used: number, cap: number, fmt: (x: number) => string, spend?: number, footprint = false) => (
    <div key={k} className={`res-item ${bump?.keys.includes(k) ? "bump" : ""}`} data-resource={k}>
      <span className="rl">{label}</span>
      <span className="rv" aria-label={footprint ? `${label}: ${fmt(used)} of ${fmt(cap)}` : `${label}: ${fmt(cap - used)} left of ${fmt(cap)}`}>{footprint ? fmt(used) : fmt(cap - used)} <span className="muted">/ {fmt(cap)}</span></span>
      <span className="meter" aria-hidden="true"><i style={{ width: `${Math.max(0, Math.min(100, ((footprint ? used : cap - used) / (cap || 1)) * 100))}%` }} /></span>
      {bump?.keys.includes(k) && spend !== undefined && spend > 0 && <span className="spend" aria-hidden="true">−{fmt(spend)}</span>}
    </div>
  );
  return (
    <div className="res" role="group" aria-label="Resources">
      {item("credits", "Quantum credits", wallet.usedCredits, wallet.credits, (x) => x.toFixed(1), lastSpend?.credits)}
      {caps.map(([k, v]) => k === "physical_qubits" && mission?.kind === "integrated"
        // qubits are a footprint (peak), not a consumable: show the executed plan's footprint against the cap
        ? item(k, "Peak qubits (footprint)", last?.totals?.qubits ?? 0, v, (x) => String(Math.round(x * 100) / 100), undefined, true)
        : item(k, RES_LABEL[k] ?? k.replace(/_/g, " "), wallet.used[k] ?? 0, v, (x) => String(Math.round(x * 100) / 100), lastSpend?.units[k]))}
      {mission?.ui?.rounds > 1 && <div className="res-item"><span className="rl">Syndrome rounds</span><span className="rv">{mission.ui.rounds}</span></div>}
      {mission?.ui?.n && <div className="res-item"><span className="rl">Core qubits</span><span className="rv">{mission.ui.n}</span></div>}
    </div>
  );
}

export function Explanation({ e }: { e?: Json }) {
  const [lvl, setLvl] = useState<"plain" | "scientific" | "math" | "refs">("plain");
  if (!e) return null;
  const tabs: ("plain" | "scientific" | "math" | "refs")[] = ["plain", "scientific", "math", "refs"];
  const label = { plain: "Summary", scientific: "Science", math: "Mathematics", refs: "Research" } as const;
  return (
    <div className="explain">
      <div role="tablist" aria-label="Explanation level" className="row tight">
        {tabs.map((t) => <button key={t} role="tab" aria-selected={lvl === t} className="tab small" onClick={() => setLvl(t)}>{label[t]}</button>)}
      </div>
      {lvl === "refs"
        ? <p>{(e.refs ?? []).length ? (e.refs as string[]).map((r, i) => <span key={r}>{i > 0 && " · "}<a href={researchUrl(r)} target="_blank" rel="noreferrer">{r}</a></span>) : "—"}</p>
        : <p>{e[lvl] || "—"}</p>}
    </div>
  );
}

/** Success/failure is conveyed by icon AND text, never by colour alone. */
export function Conditions({ items }: { items?: Json[] }) {
  if (!items?.length) return null;
  return (
    <ul className="conds" aria-label="Success conditions">
      {items.map((c) => (
        <li key={c.id} className={c.met ? "ok" : "bad"}>
          <Icon name={c.met ? "check" : "cross"} label={c.met ? "met" : "not met"} />
          <span><span className="sr-only">{c.met ? "Met: " : "Not met: "}</span>{c.text}</span>
        </li>
      ))}
    </ul>
  );
}

export function ScoreBreakdown({ sb }: { sb?: Json }) {
  if (!sb?.components) return null;
  return (
    <details>
      <summary>Why this score? (weights are game-design choices, not physical constants)</summary>
      <div className="tbl-wrap" tabIndex={0} role="region" aria-label="Score breakdown (scrollable)"><table className="tbl"><thead><tr><th>component</th><th>value</th><th>weight</th><th>contribution</th><th>kind</th></tr></thead>
        <tbody>
          {sb.components.map((c: Json) => (
            <tr key={c.name}><td title={c.note}>{c.name}</td><td className="mono">{typeof c.value === "number" ? c.value.toPrecision(4) : "n/a"}</td>
              <td>{c.weight}</td><td className="mono">{(c.contribution ?? 0).toFixed(1)}</td><td>{c.exactness}</td></tr>
          ))}
        </tbody></table></div>
    </details>
  );
}

/** Analysis shown inside a mission after an action has been executed. */
export function ResultPanel({ outcome }: { outcome: Json | null }) {
  const { state, finish, continuePlaying, mission } = useGame();
  if (!outcome) return null;
  const multi = mission && (mission.kind === "decoding" || mission.kind === "repetition");
  const ok = multi ? !!outcome.mission_success : !!outcome.success;
  const label = outcome.success ? "Goal met" : "Goal not met";
  return (
    <Panel title="Scientific analysis" accent={outcome.success ? "success" : "warning"}>
      <div className="row" role="status">
        <strong className={outcome.success ? "ok" : "bad"}><Icon name={outcome.success ? "check" : "cross"} /> {label}</strong>
        {typeof outcome.score === "number" && <span className="chip">score {outcome.score}</span>}
        <ProvenanceBadge kind={outcome.result_kind} />
      </div>
      <Conditions items={outcome.conditions} />
      <Explanation e={outcome.explanation} />
      <ScoreBreakdown sb={outcome.score_breakdown} />
      {state === "scientific_analysis" && (
        <div className="row">
          <button onClick={continuePlaying}>Adjust strategy</button>
          <button className="primary" onClick={finish}>{multi && !ok ? "Next instance" : ok || !multi ? (outcome.success || ok ? "Complete mission" : "End attempt") : "Next"}</button>
        </div>
      )}
    </Panel>
  );
}
