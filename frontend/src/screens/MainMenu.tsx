import { useState } from "react";
import { CityBackdrop, Icon, Logo } from "../art";
import { ConfirmDialog } from "../components/common";
import { useSettings } from "../settings";
import { useGame } from "../store";
import { useUi } from "../ui";

export function MainMenu() {
  const { go, progress, resetCampaign, data, apiState } = useGame();
  const { open } = useUi();
  const { sfx } = useSettings();
  const [confirmNew, setConfirmNew] = useState(false);
  const done = Object.keys(progress.completed).length;
  const hasSave = done > 0 || Object.keys(progress.failures).length > 0;
  const total = data?.missions.length ?? 29;
  const toMap = () => { sfx("confirm"); go("district_selection"); };
  const newGame = () => { setConfirmNew(false); resetCampaign(); go("district_selection"); };
  return (
    <div className="menu-wrap">
      <CityBackdrop />
      <div className="menu-panel">
        <Logo className="logo" />
        <div className="sub" aria-hidden="true">QUANTUM CITY</div>
        <nav className="menu-list" aria-label="Main menu">
          {hasSave && <button className="primary" onClick={toMap}><Icon name="play" /> Continue Campaign</button>}
          <button className={hasSave ? "" : "primary"} onClick={() => (hasSave ? setConfirmNew(true) : (sfx("confirm"), go("district_selection")))}><Icon name="star" /> New Game</button>
          <button onClick={toMap}><Icon name="map" /> City Map</button>
          <button onClick={() => open("sandbox")}><Icon name="flask" /> Scientific Sandbox</button>
          <button onClick={() => open("codex")}><Icon name="book" /> Quantum Codex</button>
          <button onClick={() => open("settings")}><Icon name="settings" /> Settings</button>
          <button onClick={() => open("credits")}><Icon name="users" /> Credits</button>
        </nav>
        <p className="menu-foot" role="status">
          {done} / {total} missions completed ·{" "}
          {apiState === "online"
            ? "Live scientific sandbox available."
            : "Live sandbox unavailable (no API reachable) — the precomputed campaign is fully playable offline. To enable the sandbox run `uvicorn qta6.api.app:app` locally."}
          {" "}Results are generated by validated quantum simulations and replayed from precomputed experiment data.
        </p>
      </div>
      {confirmNew && (
        <ConfirmDialog title="Start a new campaign?" danger confirm="Erase progress and start" onCancel={() => setConfirmNew(false)} onConfirm={newGame}
          body={<p>This replaces your saved campaign ({done} completed missions). Your settings are kept.</p>} />
      )}
    </div>
  );
}
