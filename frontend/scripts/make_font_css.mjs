// Generates src/fonts.css from the installed @fontsource packages: woff2 only. The packages list every face twice (woff2 and woff);
// every browser QTA6 supports reads woff2, so the woff fallbacks were dead weight in dist/ (~142 kB). Re-run `npm run fonts:css` after upgrading.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FACES = [["orbitron", "latin-700"], ["orbitron", "latin-900"], ["rajdhani", "latin-500"], ["rajdhani", "latin-600"], ["rajdhani", "latin-700"],
  ["inter", "latin-400"], ["inter", "latin-600"], ["jetbrains-mono", "latin-400"]];
const out = [];
for (const [pkg, face] of FACES) {
  const css = readFileSync(resolve(root, `node_modules/@fontsource/${pkg}/${face}.css`), "utf8");
  const version = JSON.parse(readFileSync(resolve(root, `node_modules/@fontsource/${pkg}/package.json`), "utf8")).version;
  const fixed = css.replace(/src:\s*url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\),\s*url\([^)]+\.woff\)\s*format\('woff'\);/g,
    (_, f) => `src: url(../node_modules/@fontsource/${pkg}/files/${f}) format('woff2');`);
  if (/\.woff\)/.test(fixed) || !/woff2/.test(fixed)) throw new Error(`unexpected font CSS for ${pkg} ${face}`);
  out.push(`/* @fontsource/${pkg}@${version} (SIL OFL 1.1) */\n${fixed.trim()}`);
}
writeFileSync(resolve(root, "src/fonts.css"), `/* GENERATED by scripts/make_font_css.mjs. Do not edit by hand. */\n${out.join("\n")}\n`);
console.log(`wrote src/fonts.css (${FACES.length} faces, woff2 only)`);
