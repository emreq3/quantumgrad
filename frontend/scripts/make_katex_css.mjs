// Generates src/math/katex.css from the installed KaTeX release.
//
// Why: the stock stylesheet lists every font three times (woff2, woff, ttf) for 20 faces; a bundler then emits all 60 files.
// Every browser QTA6 supports reads woff2, so we keep woff2 only and drop faces the game never uses (Fraktur, bold
// SansSerif/Caligraphic, Script). Layout rules are copied unchanged. Re-run `npm run math:css` after upgrading KaTeX.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(resolve(root, "node_modules/katex/package.json"), "utf8"));
const css = readFileSync(resolve(root, "node_modules/katex/dist/katex.css"), "utf8");
const KEEP = new Set(["AMS-Regular", "Caligraphic-Regular", "Main-Bold", "Main-BoldItalic", "Main-Italic", "Main-Regular", "Math-BoldItalic", "Math-Italic",
  "SansSerif-Regular", "Size1-Regular", "Size2-Regular", "Size3-Regular", "Size4-Regular", "Typewriter-Regular"]);
const faces = [];
const rest = css.replace(/@font-face\s*\{[^}]*\}/g, (block) => {
  const m = block.match(/url\(fonts\/KaTeX_([A-Za-z0-9-]+)\.woff2\)/);
  if (m && KEEP.has(m[1])) {
    faces.push(block
      .replace(/src:[^;]*;/, `src: url(../../node_modules/katex/dist/fonts/KaTeX_${m[1]}.woff2) format("woff2");`)
      .replace("font-display: block", "font-display: swap"));
  }
  return "";
}).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n{2,}/g, "\n");
const header = `/* GENERATED by scripts/make_katex_css.mjs from katex@${pkg.version} (MIT). Do not edit by hand. */\n`;
writeFileSync(resolve(root, "src/math/katex.css"), header + faces.join("\n") + "\n" + rest.trim() + "\n");
console.log(`katex@${pkg.version}: ${faces.length} woff2 faces kept, wrote src/math/katex.css`);
